// ── How much a change matters ───────────────────────────────────────────────

/**
 * Turn a 0–1 materiality score into something a person can act on.
 *
 * The score itself is never shown in the primary view. "0.85" requires the
 * reader to know the scale and where the threshold sits; "Worth acting on"
 * requires nothing. The number stays available in detail for anyone tuning a
 * threshold.
 */
export function importanceOf(materiality: number): PlainTerm {
  if (materiality >= 0.75) {
    return {
      label: 'Worth acting on',
      meaning:
        'A big change, from a source we trust, on something relevant to your current decision.',
      tone: 'warning',
    };
  }
  if (materiality >= 0.5) {
    return {
      label: 'Worth knowing',
      meaning: 'A real change, but not one that demands a response this week.',
      tone: 'caution',
    };
  }
  return {
    label: 'Minor',
    meaning:
      'Small, or from a source we trust less. Kept for the record but not worth interrupting you.',
    tone: 'neutral',
  };
}

