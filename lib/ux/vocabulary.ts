// ── How fresh something is ──────────────────────────────────────────────────

/**
 * Freshness in words rather than a timestamp.
 *
 * "Checked today" and "Last checked 47 days ago — may be out of date" both tell
 * a user what to do. A raw ISO date makes them do the arithmetic.
 */
export function freshnessOf(iso: string | null | undefined): PlainTerm {
  if (!iso) {
    return {
      label: 'Never checked',
      meaning:
        'We have not looked at this source yet, so we cannot say whether anything changed there.',
      tone: 'warning',
    };
  }

  const days = Math.floor((Date.now() - new Date(iso).getTime()) / 86_400_000);

  if (Number.isNaN(days)) {
    return { label: 'Unknown', meaning: 'We could not read the date on this.', tone: 'neutral' };
  }
  if (days <= 0) return { label: 'Checked today', meaning: 'As current as it gets.', tone: 'good' };
  if (days === 1) return { label: 'Checked yesterday', meaning: 'Still current.', tone: 'good' };
  if (days <= 7) {
    return { label: `Checked ${days} days ago`, meaning: 'Recent enough to rely on.', tone: 'good' };
  }
  if (days <= 30) {
    return {
      label: `Checked ${days} days ago`,
      meaning: 'Still reasonably current, but worth refreshing before a big decision.',
      tone: 'neutral',
    };
  }
  return {
    label: `Last checked ${days} days ago`,
    meaning: 'Old enough that it may be out of date. Refresh before relying on it.',
    tone: 'caution',
  };
}

// ── What kind of change happened ────────────────────────────────────────────

/**
 * Event types as a person would describe them.
 *
 * `pricing_changed` is a database value. "changed their pricing" is a sentence
 * fragment that reads naturally after a company name.
 */
export const EVENT_DESCRIPTION: Record<string, string> = {
  pricing_changed: 'changed their pricing',
  feature_launched: 'shipped something new',
  feature_removed: 'removed a feature',
  positioning_changed: 'changed how they describe themselves',
  segment_changed: 'shifted who they are selling to',
  integration_announced: 'announced an integration',
  hiring_signal: 'showed a hiring signal',
  funding_or_filing: 'filed or raised money',
  review_theme: 'shifted in what customers say',
  documentation_changed: 'updated their documentation',
};

export function describeEvent(eventType: string): string {
  return EVENT_DESCRIPTION[eventType] ?? eventType.replace(/_/g, ' ');
}

