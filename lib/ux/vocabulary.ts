/**
 * The single source of truth for how the product talks to a user.
 *
 * The people this is built for are founders, product marketers, and growth
 * leads — not data engineers. They should never have to translate our internal
 * vocabulary into their own. `materiality 0.85`, `entity_match: probable`, and
 * `data class: derived` are all precise and all meaningless to the person
 * making the decision.
 *
 * Everything user-facing routes through here so a term cannot drift between
 * surfaces: the same concept must read identically on a chart, in the digest,
 * and inside the evidence drawer, or the user learns three vocabularies instead
 * of none.
 *
 * The underlying distinctions are untouched. Nothing here collapses `measured`
 * into `derived` or softens a synthetic label. The rigour stays; only the
 * wording changes.
 *
 * Rules applied throughout, from the plain-language research:
 *  - Lead with a sentence, not a label.
 *  - Never show a raw score in the primary view.
 *  - One trust cue per surface, not three competing for the same glance.
 *  - Technical detail is opt-in, never removed.
 *  - State absence in words, never as a blank.
 */

export interface PlainTerm {
  /** What the user sees. */
  label: string;
  /** One sentence, shown on demand. Answers "what does that mean?" */
  meaning: string;
  /** Tone for styling. Not a value judgment about the data itself. */
  tone: 'good' | 'caution' | 'neutral' | 'warning';
}

